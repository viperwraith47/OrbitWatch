// Generates src/lib/sat/tle-snapshot.ts from fetched retlector 3LE files.
// Usage: bun scripts/gen-tle-snapshot.mjs
import { readFileSync, writeFileSync } from "node:fs";

const GROUPS = ["stations", "visual", "weather", "science", "amateur"];

function parse3le(text) {
  const lines = text.split(/\r?\n/);
  const entries = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line || line.startsWith("1 ") || line.startsWith("2 ")) {
      i += 1;
      continue;
    }
    const name = line.trimEnd();
    const l1 = (lines[i + 1] || "").trimEnd();
    const l2 = (lines[i + 2] || "").trimEnd();
    if (l1.startsWith("1 ") && l2.startsWith("2 ")) {
      const norad = parseInt(l1.substring(2, 7), 10);
      entries.push({ norad, name, line1: l1, line2: l2 });
      i += 3;
    } else {
      i += 1;
    }
  }
  return entries;
}

const out = [];
const total = {};
for (const g of GROUPS) {
  const raw = readFileSync(`/tmp/ret_${g}.3le`, "utf8");
  const entries = parse3le(raw);
  if (entries.length === 0) throw new Error(`group ${g} parsed 0 entries`);
  total[g] = entries.length;
  // validate: no backticks or ${ in data (would break template literal embedding)
  for (const e of entries) {
    for (const s of [e.name, e.line1, e.line2]) {
      if (s.includes("`") || s.includes("${")) throw new Error(`unsafe chars in ${g}: ${s}`);
    }
  }
  const normalized = entries
    .map((e) => `${e.name}\n${e.line1}\n${e.line2}`)
    .join("\n");
  out.push(`  {\n    group: ${JSON.stringify(g)},\n    text: \`\n${normalized}\n\`,\n  },`);
}

const ts = `// AUTO-GENERATED by scripts/gen-tle-snapshot.mjs — DO NOT EDIT BY HAND.
// Bundled orbital-element snapshot (3LE format) used as a fallback when live
// sources (CelesTrak via ReTLEctor mirror) are unreachable.
// Epoch of data: TLE lines themselves carry the epoch (day 305 of 2026).

export interface SnapshotGroup {
  group: string;
  text: string;
}

export const TLE_SNAPSHOT_FETCHED_AT = ${JSON.stringify(new Date().toISOString())};

export const TLE_SNAPSHOT: SnapshotGroup[] = [
${out.join("\n")}
];
`;

writeFileSync(
  "/home/z/my-project/src/lib/sat/tle-snapshot.ts",
  ts,
);
console.log("Snapshot written. Group counts:", total, "bytes:", ts.length);
